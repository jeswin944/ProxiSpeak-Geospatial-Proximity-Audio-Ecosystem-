const http = require('http');
const express = require('express');
const cors = require('cors');
const assert = require('assert');
const graphRoutes = require('./routes/graphRoutes');
const { serializeGraph } = require('../../frontend/src/utils/graphSerialization');

console.log('================================================================');
console.log('    ProxiSpeak Week 2 — End-to-End API Integration Suite       ');
console.log('================================================================\n');

async function runApiIntegrationTests() {
  const app = express();
  app.use(cors());
  app.use(express.json({ limit: '2mb' }));
  app.use('/api/graph', graphRoutes);

  const server = http.createServer(app);

  await new Promise((resolve) => server.listen(0, resolve));
  const port = server.address().port;
  const baseUrl = `http://localhost:${port}/api/graph`;
  console.log(`[Test Server] Running on ${baseUrl}\n`);

  function postJson(url, data) {
    return new Promise((resolve, reject) => {
      const payload = JSON.stringify(data);
      const req = http.request(
        url,
        {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'Content-Length': Buffer.byteLength(payload)
          }
        },
        (res) => {
          let body = '';
          res.on('data', (chunk) => (body += chunk));
          res.on('end', () => {
            try {
              resolve({ status: res.statusCode, body: JSON.parse(body) });
            } catch (err) {
              resolve({ status: res.statusCode, body });
            }
          });
        }
      );
      req.on('error', reject);
      req.write(payload);
      req.end();
    });
  }

  function getJson(url) {
    return new Promise((resolve, reject) => {
      http.get(url, (res) => {
        let body = '';
        res.on('data', (chunk) => (body += chunk));
        res.on('end', () => {
          try {
            resolve({ status: res.statusCode, body: JSON.parse(body) });
          } catch (err) {
            resolve({ status: res.statusCode, body });
          }
        });
      }).on('error', reject);
    });
  }

  const results = [];

  // Scenario 1: GET /api/graph/nodes returns registered catalog
  try {
    const res = await getJson(`${baseUrl}/nodes`);
    assert.strictEqual(res.status, 200);
    assert.strictEqual(res.body.success, true);
    assert.strictEqual(res.body.count >= 8, true);
    results.push({ test: 'GET /api/graph/nodes', status: 'PASSED', details: `Returned ${res.body.count} registered node types` });
    console.log('✓ PASS: GET /api/graph/nodes returned registered catalog');
  } catch (err) {
    results.push({ test: 'GET /api/graph/nodes', status: 'FAILED', details: err.message });
    console.error('✗ FAIL: GET /api/graph/nodes', err.message);
  }

  // Sample serialized React Flow graph payload as generated by frontend GraphEditor
  const sampleNodes = [
    { id: 'src-1', type: 'source_static', position: { x: 50, y: 100 }, data: { value: 30 } },
    { id: 'src-2', type: 'source_static', position: { x: 50, y: 250 }, data: { value: 12 } },
    { id: 'math-1', type: 'math_operation', position: { x: 300, y: 150 }, data: { operation: 'subtract' } },
    { id: 'act-alert', type: 'action_threshold_alert', position: { x: 550, y: 100 }, data: { threshold: 15, comparison: 'gt' } },
    { id: 'act-log', type: 'action_logger', position: { x: 550, y: 250 }, data: { prefix: '[E2E-TEST]' } }
  ];

  const sampleEdges = [
    { id: 'e1', source: 'src-1', target: 'math-1', sourceHandle: 'out', targetHandle: 'a' },
    { id: 'e2', source: 'src-2', target: 'math-1', sourceHandle: 'out', targetHandle: 'b' },
    { id: 'e3', source: 'math-1', target: 'act-alert', sourceHandle: 'out', targetHandle: 'in' },
    { id: 'e4', source: 'math-1', target: 'act-log', sourceHandle: 'out', targetHandle: 'in' }
  ];

  const serializedGraph = serializeGraph(sampleNodes, sampleEdges, { name: 'E2E Test Graph' });

  // Scenario 2: POST /api/graph/validate validates DAG and ports
  try {
    const res = await postJson(`${baseUrl}/validate`, serializedGraph);
    assert.strictEqual(res.status, 200);
    assert.strictEqual(res.body.success, true);
    assert.strictEqual(res.body.isValid, true);
    assert.strictEqual(res.body.nodeCount, 5);
    assert.strictEqual(res.body.edgeCount, 4);
    results.push({ test: 'POST /api/graph/validate', status: 'PASSED', details: 'Validated structure and execution order' });
    console.log('✓ PASS: POST /api/graph/validate verified graph topology');
  } catch (err) {
    results.push({ test: 'POST /api/graph/validate', status: 'FAILED', details: err.message });
    console.error('✗ FAIL: POST /api/graph/validate', err.message);
  }

  // Scenario 3: POST /api/graph/execute runs pipeline and returns results
  try {
    const res = await postJson(`${baseUrl}/execute`, { graph: serializedGraph, durationMs: 150 });
    assert.strictEqual(res.status, 200);
    assert.strictEqual(res.body.success, true);
    assert.strictEqual(typeof res.body.executionId, 'string');
    assert.strictEqual(res.body.logs.length >= 1, true);
    assert.strictEqual(res.body.logs[0].payload.result, 18, '30 - 12 must equal 18');
    assert.strictEqual(res.body.triggeredAlerts.length >= 1, true);
    assert.strictEqual(res.body.triggeredAlerts[0].breached, true, '18 > 15 must breach threshold');
    results.push({ test: 'POST /api/graph/execute', status: 'PASSED', details: `Execution ID: ${res.body.executionId}, calculated (30-12)=18, alert triggered` });
    console.log('✓ PASS: POST /api/graph/execute compiled, ran pipeline, and returned structured events');
  } catch (err) {
    results.push({ test: 'POST /api/graph/execute', status: 'FAILED', details: err.message });
    console.error('✗ FAIL: POST /api/graph/execute', err.message);
  }

  // Scenario 4: POST /api/graph/compile & POST /api/graph/stop/:id lifecycle
  try {
    const compRes = await postJson(`${baseUrl}/compile`, serializedGraph);
    assert.strictEqual(compRes.status, 200);
    assert.strictEqual(compRes.body.success, true);
    const execId = compRes.body.executionId;

    const stopRes = await postJson(`${baseUrl}/stop/${execId}`, {});
    assert.strictEqual(stopRes.status, 200);
    assert.strictEqual(stopRes.body.status, 'STOPPED');
    results.push({ test: 'Lifecycle Stop & Teardown', status: 'PASSED', details: `Cleanly stopped execution ${execId}` });
    console.log('✓ PASS: In-memory pipeline lifecycle start/stop confirmed');
  } catch (err) {
    results.push({ test: 'Lifecycle Stop & Teardown', status: 'FAILED', details: err.message });
    console.error('✗ FAIL: Lifecycle Stop & Teardown', err.message);
  }

  server.close();

  console.log('\n================================================================');
  console.log('           API INTEGRATION TEST RESULTS SUMMARY                 ');
  console.log('================================================================');
  console.table(results);

  const allPassed = results.every((r) => r.status === 'PASSED');
  if (allPassed) {
    console.log('\n🎉 ALL 4 END-TO-END API INTEGRATION SCENARIOS PASSED!\n');
    process.exit(0);
  } else {
    process.exit(1);
  }
}

runApiIntegrationTests();
